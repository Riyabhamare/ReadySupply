import { RequirementTemplate } from '../models/RequirementTemplate.js';
import { SupplierProfile } from '../models/SupplierProfile.js';
import { Document } from '../models/Document.js';
import { RequirementMapping } from '../models/RequirementMapping.js';
import { CorrectiveAction } from '../models/CorrectiveAction.js';
import { Buyer } from '../models/Buyer.js';
import { generateEvidencePackPDF } from '../services/pdfService.js';
import { logActivity } from '../services/activityService.js';
import { runMatchingEngine } from '../services/matchingEngine.js';
import { env } from '../config/env.js';

export const getPackPreview = async (req, res, next) => {
  try {
    const { templateId } = req.params;
    const supplierId = req.user._id;

    const template = await RequirementTemplate.findById(templateId).populate('buyer');
    if (!template) {
      return res.status(404).json({ error: 'NotFound', message: 'Template not found' });
    }

    const profile = await SupplierProfile.findOne({ supplier: supplierId });
    const documents = await Document.find({
      supplier: supplierId,
      isSoftDeleted: false,
    });

    let mapping = await RequirementMapping.findOne({
      supplier: supplierId,
      template: template._id,
    });

    if (!mapping) {
      // Auto run matching if not existing
      const engineResult = runMatchingEngine(template, profile, documents, {
        warningDays: env.EXPIRY_WARNING_DAYS || 30,
      });
      mapping = await RequirementMapping.create({
        supplier: supplierId,
        template: template._id,
        buyer: template.buyer._id || template.buyer,
        generatedAt: new Date(),
        readinessScore: engineResult.readinessScore,
        formula: engineResult.formula,
        disclaimer: engineResult.disclaimer,
        summary: engineResult.summary,
        results: engineResult.results,
        isDemo: profile?.isDemo || false,
      });
    }

    const actions = await CorrectiveAction.find({
      supplier: supplierId,
      $or: [{ relatedTemplate: template._id }, { relatedTemplate: null }],
    });

    // Enriched documents with computed expiry state
    const warningDays = env.EXPIRY_WARNING_DAYS || 30;
    const enrichedDocs = documents.map(d => {
      const obj = d.toObject();
      obj.expiryInfo = d.computeExpiryState(warningDays);
      return obj;
    });

    res.json({
      profile,
      template,
      buyer: template.buyer,
      mapping,
      documents: enrichedDocs,
      actions,
      disclaimer: 'Preparation document generated by ReadySupply. Not a certification or supplier approval. Final approval rests with the buyer.',
    });
  } catch (err) {
    next(err);
  }
};

export const exportPackPDF = async (req, res, next) => {
  try {
    const { templateId } = req.params;
    const supplierId = req.user._id;

    const template = await RequirementTemplate.findById(templateId).populate('buyer');
    if (!template) {
      return res.status(404).json({ error: 'NotFound', message: 'Template not found' });
    }

    const profile = await SupplierProfile.findOne({ supplier: supplierId });
    const documents = await Document.find({ supplier: supplierId, isSoftDeleted: false });
    const mapping = await RequirementMapping.findOne({ supplier: supplierId, template: template._id });
    const actions = await CorrectiveAction.find({
      supplier: supplierId,
      $or: [{ relatedTemplate: template._id }, { relatedTemplate: null }],
    });

    const filename = `ReadySupply_Dossier_${(profile?.companyName || 'Supplier').replace(/[^a-zA-Z0-9]/g, '_')}.pdf`;

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

    await generateEvidencePackPDF({
      supplierProfile: profile || { companyName: req.user.name },
      supplierUser: req.user,
      buyer: template.buyer,
      template,
      mapping,
      documents,
      actions,
      outputStream: res,
    });

    await logActivity({
      supplierId,
      performedById: req.user._id,
      action: 'EXPORT_PDF',
      entityType: 'EvidencePack',
      entityId: template._id.toString(),
      details: { templateName: template.name },
      ip: req.ip,
    });
  } catch (err) {
    next(err);
  }
};

