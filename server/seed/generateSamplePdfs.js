import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import PDFDocument from 'pdfkit';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const uploadDir = path.resolve(__dirname, '../uploads/private');

if (!fs.existsSync(uploadDir)) {
  fs.mkdirSync(uploadDir, { recursive: true });
}

/**
 * Creates a sample PDF document marked clearly as FICTIONAL DEMO EVIDENCE
 */
export const createSamplePdf = async ({ title, category, entityName, validityText }) => {
  return new Promise((resolve, reject) => {
    const filename = `${crypto.randomUUID()}.pdf`;
    const targetPath = path.join(uploadDir, filename);
    const writeStream = fs.createWriteStream(targetPath);

    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    doc.pipe(writeStream);

    // Header banner
    doc.rect(50, 50, 495, 60).fill('#0B1F44');
    doc.fillColor('#FFFFFF').fontSize(18).font('Helvetica-Bold').text('SAMPLE DOCUMENT - FICTIONAL', 70, 65);
    doc.fontSize(10).font('Helvetica').text('ReadySupply MSME Demonstration Evidence', 70, 88);

    doc.moveDown(4);

    // Notice box
    doc.rect(50, 130, 495, 45).fillAndStroke('#FEF3C7', '#F59E0B');
    doc.fillColor('#92400E').fontSize(9).font('Helvetica-Bold')
      .text('FICTIONAL TEST DATA NOTICE:', 65, 140);
    doc.fontSize(8.5).font('Helvetica')
      .text('This document was automatically generated by ReadySupply for demonstration and testing purposes. It does not represent a real commercial entity or formal certification.', 65, 153, { width: 460 });

    doc.moveDown(3);

    // Document Body
    doc.fillColor('#0F172A').fontSize(16).font('Helvetica-Bold').text(title, 50, 200);
    doc.rect(50, 222, 495, 1).fill('#E2E8F0');

    doc.moveDown(1.5);
    doc.fontSize(10).font('Helvetica').fillColor('#334155');
    doc.text(`Issuing Authority / Agency: National Testing & Standards Board (Fictional)`);
    doc.text(`Issued To Enterprise: ${entityName}`);
    doc.text(`Category of Record: ${category}`);
    doc.text(`Validity / Expiration: ${validityText || 'Indefinite'}`);
    doc.text(`Document Reference Number: RS-DEMO-${Math.floor(100000 + Math.random() * 900000)}`);

    doc.moveDown(2);
    doc.text('Verification Checklist Summary:');
    doc.fontSize(9).font('Helvetica').fillColor('#64748B');
    doc.text('• Formal entity registration details match declared records.');
    doc.text('• Technical scope meets standard manufacturing and inspection thresholds.');
    doc.text('• Quality assurance sign-off executed by authorized technical personnel.');

    // Watermark
    doc.fontSize(36).font('Helvetica-Bold').fillColor('#E2E8F0', 0.25)
      .text('FICTIONAL SAMPLE', 100, 450, { rotation: 30, align: 'center' });

    // Footer
    doc.rect(50, 750, 495, 0.5).fill('#CBD5E1');
    doc.fillColor('#94A3B8').fontSize(8).font('Helvetica')
      .text('ReadySupply Demo Record - For evaluation purposes only', 50, 760, { align: 'center', width: 495 });

    doc.end();

    writeStream.on('finish', () => {
      const stats = fs.statSync(targetPath);
      resolve({
        filename,
        storagePath: targetPath,
        size: stats.size,
      });
    });

    writeStream.on('error', (err) => reject(err));
  });
};

